"""Name the Rust syntax kinds consumed by the module ownership checker."""

from enum import StrEnum


class NodeKind(StrEnum):
    """Identify a node in Tree-sitter's Rust grammar."""

    ATTRIBUTE_ITEM = "attribute_item"
    BLOCK = "block"
    BLOCK_COMMENT = "block_comment"
    BRACKETED_TYPE = "bracketed_type"
    CLOSURE_EXPRESSION = "closure_expression"
    CRATE = "crate"
    DECLARATION_LIST = "declaration_list"
    EXTERN_CRATE_DECLARATION = "extern_crate_declaration"
    FOR_EXPRESSION = "for_expression"
    FUNCTION_ITEM = "function_item"
    GENERIC_TYPE = "generic_type"
    IDENTIFIER = "identifier"
    IMPL_ITEM = "impl_item"
    INNER_ATTRIBUTE_ITEM = "inner_attribute_item"
    LET_CONDITION = "let_condition"
    LET_DECLARATION = "let_declaration"
    LINE_COMMENT = "line_comment"
    MATCH_ARM = "match_arm"
    MOD_ITEM = "mod_item"
    PARAMETER = "parameter"
    QUALIFIED_TYPE = "qualified_type"
    SCOPED_IDENTIFIER = "scoped_identifier"
    SCOPED_TYPE_IDENTIFIER = "scoped_type_identifier"
    SCOPED_USE_LIST = "scoped_use_list"
    SELF = "self"
    SOURCE_FILE = "source_file"
    STRING_LITERAL = "string_literal"
    SUPER = "super"
    MACRO_INPUT = "token_tree"
    TYPE_ARGUMENTS = "type_arguments"
    TYPE_IDENTIFIER = "type_identifier"
    TYPE_ITEM = "type_item"
    USE_AS_CLAUSE = "use_as_clause"
    USE_DECLARATION = "use_declaration"
    USE_LIST = "use_list"
    USE_WILDCARD = "use_wildcard"
    VISIBILITY_MODIFIER = "visibility_modifier"
